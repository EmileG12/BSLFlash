import { supabase } from './supabase'

export interface SignVideoMetadata {
  durationMs: number
  width: number
  height: number
}

export interface UploadedSignVideoFile {
  storagePath: string
  format: 'mp4' | 'webm'
  metadata: SignVideoMetadata
}

function readVideoMetadata(file: File): Promise<SignVideoMetadata> {
  return new Promise((resolve, reject) => {
    const video = document.createElement('video')
    video.preload = 'metadata'
    video.onloadedmetadata = () => {
      URL.revokeObjectURL(video.src)
      resolve({
        durationMs: Math.round(video.duration * 1000),
        width: video.videoWidth,
        height: video.videoHeight,
      })
    }
    video.onerror = () => {
      URL.revokeObjectURL(video.src)
      reject(new Error('Could not read the video file.'))
    }
    video.src = URL.createObjectURL(file)
  })
}

function videoFormatFor(file: File): 'mp4' | 'webm' | null {
  if (file.type === 'video/mp4') return 'mp4'
  if (file.type === 'video/webm') return 'webm'
  return null
}

/**
 * Uploads a video file to the sign-videos bucket under the given sign id and
 * returns what's needed to write the matching sign_videos row -- it does not
 * write that row itself. Writing the DB row is left to one of the atomic
 * add_*_with_video/add_video_to_sign RPCs, so that a failure there can be
 * told apart from a failure here, and so the caller can clean up this
 * upload (via deleteSignVideoFile) if the RPC fails. signId is generated by
 * the caller before the row it belongs to exists, so the conventional
 * <sign_id>/<file>.<ext> storage path can be built before upload.
 */
export async function uploadSignVideoFile(signId: string, file: File): Promise<UploadedSignVideoFile> {
  const format = videoFormatFor(file)
  if (!format) {
    throw new Error('Video must be an mp4 or webm file.')
  }

  const metadata = await readVideoMetadata(file)
  const storagePath = `${signId}/${crypto.randomUUID()}.${format}`

  const { error } = await supabase.storage.from('sign-videos').upload(storagePath, file, { contentType: file.type })
  if (error) throw error

  return { storagePath, format, metadata }
}

/**
 * Removes a video object from the sign-videos bucket. Used to compensate
 * for a successful uploadSignVideoFile when the atomic RPC that was meant to
 * write its DB row fails, so the overall add-word/add-variant/add-video
 * operation leaves nothing behind on failure. Throws if the delete itself
 * fails, OR if it reports no error but removed nothing -- which is exactly
 * what the Storage API returns when RLS silently filters the object out
 * (e.g. an admin, who can upload but isn't covered by the superadmin-only
 * delete policy, tries to clean up their own failed upload) -- so the
 * caller can tell a clean rollback apart from an orphaned file that needs
 * manual cleanup.
 */
export async function deleteSignVideoFile(storagePath: string): Promise<void> {
  const { data, error } = await supabase.storage.from('sign-videos').remove([storagePath])
  if (error) throw error
  if (!data || data.length === 0) {
    throw new Error('The video file was not removed (no object was deleted).')
  }
}
